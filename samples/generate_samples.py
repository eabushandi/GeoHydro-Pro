"""Generate the synthetic sample datasets shipped with GeoHydro Pro.

All datasets are SYNTHETIC. They are produced from documented analytic
functions with a fixed random seed so that they are reproducible and can be
used as reference data in automated tests and later numerical validation
(e.g. comparing interpolated grids against the known generating surface).
They are not real field observations.

Run:  python samples/generate_samples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE / "data"
SEED = 20261119

# UTM zone 39N (EPSG:32639) window, roughly the size of a 10 km x 10 km site
X0, Y0 = 440_000.0, 2_885_000.0
SIZE = 10_000.0


def terrain_surface(x, y):
    """Reference terrain z(x, y) in metres (documented in samples/README.md)."""
    u = (x - X0) / SIZE
    v = (y - Y0) / SIZE
    z = 4.0 + 6.0 * u + 3.0 * v
    z += 22.0 * np.exp(-((u - 0.35) ** 2 + (v - 0.60) ** 2) / (2 * 0.12 ** 2))
    z += 11.0 * np.exp(-((u - 0.75) ** 2 + (v - 0.30) ** 2) / (2 * 0.08 ** 2))
    z -= 6.0 * np.exp(-((u - 0.60) ** 2 + (v - 0.75) ** 2) / (2 * 0.10 ** 2))
    return z


def groundwater_head(x, y):
    """Water table (m above mean sea level): regional gradient plus a recharge mound."""
    u = (x - X0) / SIZE
    v = (y - Y0) / SIZE
    return 1.5 + 4.0 * (1 - u) + 1.2 * np.exp(-((u - 0.4) ** 2 + (v - 0.5) ** 2) / (2 * 0.15 ** 2))


def make_terrain(rng):
    n = 300
    x = X0 + rng.uniform(0, SIZE, n)
    y = Y0 + rng.uniform(0, SIZE, n)
    z = terrain_surface(x, y) + rng.normal(0, 0.15, n)
    dates = pd.Timestamp("2026-03-02") + pd.to_timedelta(rng.integers(0, 12, n), unit="D")
    df = pd.DataFrame({
        "Point_ID": [f"TS{i + 1:04d}" for i in range(n)],
        "Easting_m": np.round(x, 3),
        "Northing_m": np.round(y, 3),
        "Elevation_m": np.round(z, 3),
        "Survey_Date": dates.strftime("%Y-%m-%d"),
    })
    df.to_csv(OUT / "terrain_survey_utm39n.csv", index=False)
    return df


def make_wells(rng):
    n = 60
    x = X0 + rng.uniform(500, SIZE - 500, n)
    y = Y0 + rng.uniform(500, SIZE - 500, n)
    h = groundwater_head(x, y) + rng.normal(0, 0.05, n)
    tds = 900 + 2600 * ((x - X0) / SIZE) ** 1.5 + rng.normal(0, 60, n)
    df = pd.DataFrame({
        "Well_ID": [f"MW-{i + 1:02d}" for i in range(n)],
        "X (m)": np.round(x, 2),
        "Y (m)": np.round(y, 2),
        "Water_Level_mAMSL": np.round(h, 3),
        "TDS_mgL": np.round(tds, 0),
        "Measured": pd.Timestamp("2026-10-15").date(),
    })
    notes = pd.DataFrame({
        "Notes": [
            "SYNTHETIC groundwater monitoring dataset generated by samples/generate_samples.py",
            "CRS: EPSG:32639 (WGS 84 / UTM zone 39N). Units: metres; TDS in mg/L.",
            "Water level = 1.5 + 4.0*(1-u) + 1.2*exp(-((u-0.4)^2+(v-0.5)^2)/(2*0.15^2)) + N(0, 0.05)",
        ]
    })
    with pd.ExcelWriter(OUT / "groundwater_wells.xlsx", engine="openpyxl") as xw:
        df.to_excel(xw, sheet_name="Wells", index=False)
        notes.to_excel(xw, sheet_name="Notes", index=False)
    return df


def make_bathymetry(rng):
    n = 2000
    x = X0 + rng.uniform(0, 4000, n)
    y = Y0 + rng.uniform(0, 3000, n)
    offshore = (y - Y0)  # shoreline along y = Y0, deepening northwards
    depth = -0.3 - 0.0035 * offshore + 0.8 * np.exp(-((offshore - 600) ** 2) / (2 * 120 ** 2))
    depth += 0.4 * np.sin((x - X0) / 400.0) * np.exp(-offshore / 1500)
    depth += rng.normal(0, 0.05, n)
    with open(OUT / "bathymetry_nearshore.xyz", "w", newline="\n") as fh:
        for a, b, c in zip(x, y, depth):
            fh.write(f"{a:.2f} {b:.2f} {c:.3f}\n")


def make_errors(rng):
    """Semicolon-delimited, decimal-comma file with deliberate data problems."""
    rows = []
    for i in range(40):
        x = X0 + 1000 + rng.uniform(0, 3000)
        y = Y0 + 1000 + rng.uniform(0, 3000)
        z = terrain_surface(x, y)
        rows.append([f"P{i + 1:02d}", f"{x:.2f}", f"{y:.2f}", f"{z:.2f}"])
    rows[3][3] = ""            # missing Z
    rows[7][3] = "-9999"       # NoData sentinel
    rows[11][1] = "n/a"        # missing X (token)
    rows[15][2] = "4521x88"    # non-numeric Y (typo)
    rows[19][3] = "NaN"        # missing Z token
    rows[24] = [rows[24][0], rows[5][1], rows[5][2], rows[24][3]]  # duplicate location, different Z
    rows[30] = [rows[30][0], rows[9][1], rows[9][2], rows[9][3]]   # exact duplicate
    with open(OUT / "field_readings_with_errors.csv", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("Station;East;North;Level\n")
        for r in rows:
            fh.write(";".join(c.replace(".", ",") for c in r) + "\n")


def make_stations(rng):
    n = 50
    lon = 50.45 + rng.uniform(0, 0.15, n)
    lat = 26.00 + rng.uniform(0, 0.20, n)
    temp = 24.0 + 3.0 * (lat - 26.0) / 0.2 + rng.normal(0, 0.3, n)
    df = pd.DataFrame({"Station": [f"ST{i + 1:02d}" for i in range(n)],
                       "Longitude": np.round(lon, 6), "Latitude": np.round(lat, 6),
                       "SST_degC": np.round(temp, 2)})
    df.loc[17, "Latitude"] = 126.0512  # deliberate out-of-range latitude (typo)
    df.to_csv(OUT / "stations_wgs84.dat", sep="\t", index=False)


def make_contaminant(rng):
    n = 80
    x = X0 + rng.uniform(2000, 6000, n)
    y = Y0 + rng.uniform(2000, 6000, n)
    r2 = (x - (X0 + 3500)) ** 2 + (y - (Y0 + 4200)) ** 2
    c = 850.0 * np.exp(-r2 / (2 * 700.0 ** 2)) + np.abs(rng.normal(0, 2, n))
    with open(OUT / "contaminant_survey.txt", "w", newline="\n") as fh:
        fh.write("# SYNTHETIC benzene plume survey (GeoHydro Pro sample data)\n")
        fh.write("# CRS: EPSG:32639  units: m ; concentration ug/L\n")
        fh.write("# C = 850*exp(-r^2/(2*700^2)) + |N(0,2)|\n")
        fh.write("SampleID  X  Y  Benzene_ugL\n")
        for i, (a, b, v) in enumerate(zip(x, y, c)):
            fh.write(f"BH{i + 1:03d}  {a:.1f}  {b:.1f}  {v:.2f}\n")


def make_sample_project():
    sys.path.insert(0, str(HERE.parent))
    from geohydro.engine.data import ImportSettings, import_point_file
    from geohydro.engine.data.importer import apply_crs
    from geohydro.project import Project, save_project

    proj = Project(name="Sample Site Investigation", author="GeoHydro Pro samples",
                   description="Synthetic demonstration project (terrain survey and monitoring wells).",
                   default_crs="EPSG:32639")
    s = apply_crs(ImportSettings("Easting_m", "Northing_m", "Elevation_m"), "EPSG:32639")
    proj.add_dataset(import_point_file(OUT / "terrain_survey_utm39n.csv", settings=s, name="Terrain survey"))
    s = apply_crs(ImportSettings("X (m)", "Y (m)", "Water_Level_mAMSL"), "EPSG:32639")
    wells = proj.add_dataset(import_point_file(OUT / "groundwater_wells.xlsx", settings=s,
                                               name="Monitoring wells"))
    _add_sample_grids_and_maps(proj, proj.dataset_by_name("Terrain survey"), wells)
    target = HERE / "sample_project.ghproj"
    if target.exists():
        target.unlink()
    save_project(proj, target)
    for p in HERE.glob("sample_project.ghproj.bak"):
        p.unlink()


def _add_sample_grids_and_maps(proj, terrain, wells):
    """Phase 2 content: a minimum-curvature terrain grid, a kriged head grid and two maps."""
    from geohydro.engine.gridding.gridder import BlankingOptions, GriddingRequest, grid_data
    from geohydro.engine.gridding.grid import GridGeometry
    from geohydro.engine.interpolation.variogram import experimental_variogram, fit_variogram
    from geohydro.engine.mapping.levels import LevelSpec
    from geohydro.engine.mapping.model import (ColourReliefLayer, ContourLayer,
                                               FilledContourLayer, MapDocument, PostLayer)

    def run(ds, request, name):
        d = ds.data
        x, y, z = (d[c].to_numpy(float) for c in ("X", "Y", "Z"))
        src = {"dataset_id": ds.id, "dataset_name": ds.name, "z_column": ds.z_label}
        return proj.add_grid(grid_data(x, y, z, request, name=name, crs=ds.crs,
                                       xy_units=ds.xy_units, z_units=ds.z_units,
                                       z_label=ds.z_label, source=src).grid)

    d = terrain.data
    geom = GridGeometry.from_points(d["X"], d["Y"], n_long=120)
    tg = run(terrain, GriddingRequest("min_curvature", {"tension": 0.25}, geom,
                                      BlankingOptions(outside_hull=True)), "Terrain (min. curvature)")
    # The heads carry a strong regional gradient, so a variogram of the raw values never
    # levels off. Universal kriging with a linear drift is used, with the variogram
    # fitted to the residuals from a least-squares plane (the usual practical approach).
    w = wells.data
    x, y, z = (w[c].to_numpy(float) for c in ("X", "Y", "Z"))
    A = np.c_[np.ones_like(x), x - x.mean(), y - y.mean()]
    resid = z - A @ np.linalg.lstsq(A, z, rcond=None)[0]
    model, rep = fit_variogram(experimental_variogram(x, y, resid), "spherical")
    assert not rep.get("warnings"), rep.get("warnings")
    geom = GridGeometry.from_points(w["X"], w["Y"], n_long=80, margin=0.05)
    hg = run(wells, GriddingRequest("universal_kriging",
                                    {"variogram": model.to_dict(), "drift": "linear"}, geom,
                                    BlankingOptions(outside_hull=True)),
             "Groundwater head (kriging)")
    proj.add_map(MapDocument(
        name="Terrain relief map", title="Terrain surface", subtitle="Minimum curvature, tension 0.25",
        crs=tg.crs, layers=[ColourReliefLayer(grid_id=tg.id, name="Colour relief"),
                            ContourLayer(grid_id=tg.id, name="Contours", line_width=0.4,
                                         major_width=0.9, levels=LevelSpec("interval", interval=5)),
                            PostLayer(dataset_id=terrain.id, name="Survey points", size=3,
                                      face_color="#111111")]))
    proj.add_map(MapDocument(
        name="Groundwater head map", title="Groundwater head",
        subtitle="Universal kriging, linear drift (variogram fitted to detrended heads)",
        crs=hg.crs, layers=[FilledContourLayer(grid_id=hg.id, name="Filled contours",
                                               palette="viridis"),
                            ContourLayer(grid_id=hg.id, name="Head contours", labels=True),
                            PostLayer(dataset_id=wells.id, name="Wells", label_column="Well_ID")]))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)
    make_terrain(rng)
    make_wells(rng)
    make_bathymetry(rng)
    make_errors(rng)
    make_stations(rng)
    make_contaminant(rng)
    make_sample_project()
    print(f"Sample data written to {OUT}")


if __name__ == "__main__":
    main()
